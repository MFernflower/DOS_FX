USE16
ORG 0x100
PUSH WORD 0x0B800  
POP ES           
XOR DI,DI 
MOV CX,0x07D0
; MOV AX,0x0110 
XOR AX,AX
WRITEMEM:
INC AX
STOSW 
LOOP WRITEMEM
KEYEXIT:
MOV AH,0x01 ; CHECK IF KEY TOUCHED
INT 0x16   ; CHECK IF KEY TOUCHED
JZ KEYEXIT  ; IF NOT WE START ALLOVER AGAIN
MOV AX,0x0002 ; CLEAR SCREEN
INT 0x10 ; CLEAR SCREEN
MOV AX,0x4C00 ; exit back to dos the safe way
INT 0x21      ; do it
FINGERPRINT DB 0xFF,0xBA,0xDA
